const assert = require('node:assert/strict');
const { createScreenshotShortcut, DEFAULT_SCREENSHOT_SHORTCUT } = require('../src/core/screenshot-shortcut');
const registrations = new Map();
const shortcut = createScreenshotShortcut({ register: (key, callback) => { if (key === 'Control+Alt+B') return false; registrations.set(key, callback); return true; }, unregister: key => registrations.delete(key) }, () => {});
shortcut.registerInitial();
assert.equal(shortcut.getState().registered, true);
assert.ok(registrations.has(DEFAULT_SCREENSHOT_SHORTCUT));
assert.throws(() => shortcut.setShortcut('Control+Alt+B'), /占用/);
assert.ok(registrations.has(DEFAULT_SCREENSHOT_SHORTCUT), 'failed changes preserve the old working binding');
assert.throws(() => shortcut.setShortcut('A'), /组合键/);
shortcut.setShortcut('Control+Shift+F9');
assert.equal(registrations.has(DEFAULT_SCREENSHOT_SHORTCUT), false);
assert.equal(registrations.has('Control+Shift+F9'), true);
let registerCalls = 0;
const alias = createScreenshotShortcut({ register: () => ++registerCalls === 1, unregister: () => {} }, () => {}, 'darwin');
alias.registerInitial();
alias.setShortcut('Alt+Command+A');
assert.equal(registerCalls, 1, 'recording the currently bound physical shortcut must not re-register it under a different alias/order');
alias.dispose();
shortcut.dispose();
assert.equal(registrations.size, 0);
console.log('Global screenshot shortcut tests passed.');
